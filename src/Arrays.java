public class Arrays {
    public static void main(String[] args) {
         int age = 20;
         int numbers[] = {10,20,30,40,50}; 
         System.out.println(age);// 20
         System.out.println(numbers[0]);
         System.out.println(numbers[2]);
         for (int i = 0; i < 5; i++){
            System.out.println(numbers[i]);
         }
    }
}
